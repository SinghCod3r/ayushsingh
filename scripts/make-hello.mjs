// Converts the intro word into SVG outlines so the "hello" intro can draw it.
// Run: node scripts/make-hello.mjs   (output: src/lib/hello-paths.ts)
import opentype from "opentype.js";
import { writeFileSync, readFileSync } from "node:fs";

const TEXT = "singhcod3r";
const SIZE = 220;
const fontPath =
  "node_modules/@fontsource/mr-dafoe/files/mr-dafoe-latin-400-normal.woff";

const buf = readFileSync(fontPath);
const font = opentype.parse(
  buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength),
);

const scale = SIZE / font.unitsPerEm;
let x = 0;
const glyphs = [];
let minX = Infinity,
  minY = Infinity,
  maxX = -Infinity,
  maxY = -Infinity;

for (const ch of TEXT) {
  const glyph = font.charToGlyph(ch);
  const path = glyph.getPath(x, 0, SIZE);
  const bb = path.getBoundingBox();
  if (isFinite(bb.x1)) {
    minX = Math.min(minX, bb.x1);
    minY = Math.min(minY, bb.y1);
    maxX = Math.max(maxX, bb.x2);
    maxY = Math.max(maxY, bb.y2);
  }
  glyphs.push(path.toPathData(1));
  x += glyph.advanceWidth * scale;
}

const pad = 12;
const out = `// Generated by scripts/make-hello.mjs — do not edit by hand.
export const HELLO_VIEWBOX = "${(minX - pad).toFixed(1)} ${(minY - pad).toFixed(1)} ${(maxX - minX + pad * 2).toFixed(1)} ${(maxY - minY + pad * 2).toFixed(1)}";
export const HELLO_GLYPHS: string[] = ${JSON.stringify(glyphs.filter(Boolean), null, 2)};
`;
writeFileSync("src/lib/hello-paths.ts", out);
console.log("glyphs:", glyphs.length, "viewBox:", out.match(/HELLO_VIEWBOX = "(.*)"/)[1]);
